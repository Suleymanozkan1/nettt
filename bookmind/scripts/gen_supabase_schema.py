#!/usr/bin/env python3
"""
Generates the Supabase (PostgreSQL) tables for synced data from Room's exported schema, so the server always
has exactly the columns the Android client pushes (camelCase -> snake_case).

Usage: python3 scripts/gen_supabase_schema.py app/schemas/com.bookmind.app.data.db.BookMindDatabase/2.json > supabase/migrations/<ts>_synced_tables.sql

Rules:
- Every table gets user_id uuid NOT NULL DEFAULT auth.uid() (the client never sends it) and a server-maintained
  server_updated_at used for incremental pulls.
- Local userId columns are dropped (replaced by user_id); device-local columns are skipped.
- Foreign keys become composite (child_col, user_id) -> parent(id, user_id) so a row can only reference the same
  user's rows, even though foreign-key checks bypass row level security.
- RLS: a user can only see and change rows whose user_id = auth.uid().
"""
import json
import re
import sys

SYNCED = [
    "books", "book_sources", "chapters", "concepts", "summaries", "learning_items", "review_states", "review_logs",
    "quizzes", "quiz_questions", "quiz_attempts", "quiz_answers", "study_sessions", "user_notes",
    "notification_preferences", "xp_events", "study_plans", "plan_tasks", "concept_links",
]
BOOLEAN = {
    "isDemo", "isPrerequisite", "isFavorite", "userEdited", "suspended", "hintUsed", "needsReview", "correct",
    "inReviewQueue", "enabled", "showContent", "fromBook", "aiDerived", "done",
}
LOCAL_ONLY = {"chapters": {"textFile"}}


def snake(name: str) -> str:
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower()


def main(path: str) -> None:
    schema = json.load(open(path))["database"]
    entities = {e["tableName"]: e for e in schema["entities"]}
    out = [
        "-- GENERATED by scripts/gen_supabase_schema.py from Room schema version %d. Do not edit by hand." % schema["version"],
        "-- Synced tables mirror the Android Room schema; see docs/DATA_MODEL.md.",
        "",
    ]
    for table in SYNCED:
        e = entities[table]
        cols = []
        for f in e["fields"]:
            name = f["columnName"]
            if name == "userId" or name in LOCAL_ONLY.get(table, set()):
                continue
            if name in BOOLEAN:
                sqltype = "boolean"
            elif f["affinity"] == "INTEGER":
                sqltype = "bigint"
            elif f["affinity"] == "REAL":
                sqltype = "double precision"
            else:
                sqltype = "text"
            null = " not null" if f.get("notNull") else ""
            default = ""
            if f.get("defaultValue") is not None and name in BOOLEAN:
                default = " default " + ("true" if f["defaultValue"] in ("1", "true") else "false")
            cols.append("  %s %s%s%s" % (snake(name), sqltype, null, default))
        cols.append("  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade")
        cols.append("  server_updated_at timestamptz not null default now()")
        cols.append("  primary key (id)")
        cols.append("  unique (id, user_id)")
        for fk in e.get("foreignKeys", []):
            child = [snake(c) for c in fk["columns"]]
            parent = [snake(c) for c in fk["referencedColumns"]]
            action = fk["onDelete"].lower()
            if action == "set null":
                on_delete = "on delete set null (%s)" % ", ".join(child)
            elif action == "cascade":
                on_delete = "on delete cascade"
            else:
                on_delete = "on delete no action"
            cols.append(
                "  foreign key (%s, user_id) references public.%s (%s, user_id) %s"
                % (", ".join(child), fk["table"], ", ".join(parent), on_delete)
            )
        for idx in e.get("indices", []):
            if idx.get("unique"):
                columns = ["user_id" if c == "userId" else snake(c) for c in idx["columnNames"]]
                if "user_id" not in columns:
                    columns.append("user_id")
                cols.append("  unique (%s)" % ", ".join(columns))
        out.append("create table public.%s (\n%s\n);" % (table, ",\n".join(cols)))
        out.append("create index %s_user_sync_idx on public.%s (user_id, server_updated_at);" % (table, table))
        for fk in e.get("foreignKeys", []):
            child = [snake(c) for c in fk["columns"]]
            out.append("create index %s_%s_fk_idx on public.%s (%s, user_id);" % (table, "_".join(child), table, ", ".join(child)))
        out.append("alter table public.%s enable row level security;" % table)
        for op, clause in (
            ("select", "using (user_id = auth.uid())"),
            ("insert", "with check (user_id = auth.uid())"),
            ("update", "using (user_id = auth.uid()) with check (user_id = auth.uid())"),
            ("delete", "using (user_id = auth.uid())"),
        ):
            out.append("create policy %s_%s_own on public.%s for %s to authenticated %s;" % (table, op, table, op, clause))
        out.append(
            "create trigger %s_touch before insert or update on public.%s for each row execute function public.touch_server_updated_at();"
            % (table, table)
        )
        out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
